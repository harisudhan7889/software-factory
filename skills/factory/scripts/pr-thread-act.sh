#!/bin/bash
#
# pr-thread-act.sh — post a reply to, or resolve, one PR review thread.
#
# These two actions change a Pull Request other people read. Callers MUST get
# the user's approval of the exact text first (see
# skills/factory/references/address-comments.md, Phase 9). This script only
# performs the approved action; it never decides one.
#
# Usage:
#   pr-thread-act.sh reply   <thread-node-id> --body "<text>"
#   pr-thread-act.sh reply   <thread-node-id> --body-file <path>
#   pr-thread-act.sh resolve <thread-node-id>
#
# `reply` appends the AI-generated disclaimer to every reply, so the label is
# deterministic and cannot be forgotten. A reply identical to the thread's
# latest comment is skipped, so a retry does not post a duplicate.
#
# Output: one line — REPLIED <url> | SKIPPED duplicate reply | RESOLVED

set -euo pipefail

DISCLAIMER='*This reply was generated by an AI agent.*'

usage() {
    echo "Usage: pr-thread-act.sh reply <thread-node-id> --body <text> | --body-file <path>" >&2
    echo "       pr-thread-act.sh resolve <thread-node-id>" >&2
    exit 1
}

[ "$#" -ge 2 ] || usage

for tool in gh jq; do
    command -v "$tool" >/dev/null 2>&1 || { echo "Error: $tool is required." >&2; exit 1; }
done

ACTION="$1"
THREAD_ID="$2"
shift 2

case "$ACTION" in
    reply)
        BODY=""
        while [ "$#" -gt 0 ]; do
            case "$1" in
                --body)      [ "$#" -ge 2 ] || usage; BODY="$2"; shift 2 ;;
                --body-file) [ "$#" -ge 2 ] || usage; BODY="$(cat "$2")"; shift 2 ;;
                *) usage ;;
            esac
        done
        if [ -z "${BODY//[[:space:]]/}" ]; then
            echo "Error: reply body is empty." >&2
            exit 1
        fi
        FINAL="$BODY"$'\n\n'"$DISCLAIMER"

        LAST=$(gh api graphql -f query='
            query($id: ID!) {
              node(id: $id) {
                ... on PullRequestReviewThread {
                  comments(last: 1) { nodes { body } }
                }
              }
            }' -f id="$THREAD_ID" --jq '.data.node.comments.nodes[0].body // ""')
        if [ "$LAST" = "$FINAL" ]; then
            echo "SKIPPED duplicate reply"
            exit 0
        fi

        URL=$(gh api graphql -f query='
            mutation($id: ID!, $body: String!) {
              addPullRequestReviewThreadReply(input: {pullRequestReviewThreadId: $id, body: $body}) {
                comment { url }
              }
            }' -f id="$THREAD_ID" -f body="$FINAL" \
            --jq '.data.addPullRequestReviewThreadReply.comment.url')
        echo "REPLIED $URL"
        ;;
    resolve)
        [ "$#" -eq 0 ] || usage
        STATE=$(gh api graphql -f query='
            mutation($id: ID!) {
              resolveReviewThread(input: {threadId: $id}) { thread { isResolved } }
            }' -f id="$THREAD_ID" --jq '.data.resolveReviewThread.thread.isResolved')
        if [ "$STATE" = "true" ]; then echo "RESOLVED"; else echo "Error: thread was not resolved." >&2; exit 1; fi
        ;;
    *)
        usage
        ;;
esac
